    private void limpiarCampos() {
        fabricantes = null;
        try {
            fabricantes = new FabricanteService().getAllFabricantesOrdenadoActivos();
        } catch (Exception ex) {
            Logger.getLogger(NuevoStockFrame.class.getName()).log(Level.SEVERE, null, ex);
        }
        comboF.removeAllItems();
        comboF.addItem("");
        for (Fabricante f : fabricantes) {
            comboF.addItem(f.getNombre());
        }
//        proveedorTxt.setText("");
        comprobanteTxt.setText("");
        fechaTxt.setText("");
        combo.removeAllItems();
        filtroTxt.setText("");
        finalTxt.setText("");
        cantidadTxt.setText("");
        actualizarChk.setSelected(false);
        precioTxt.setText("");
        impuestoTxt.setText("");
        precioTxt.setEditable(false);
        impuestoTxt.setEditable(false);
    }

    private void llenarCombo() {
        combo.removeAllItems();
        combo.addItem("");
        String filtro = filtroTxt.getText();
        productos = null;
        try {
            productos = new ProductoService().getAllProductosOrdenadoByNombre(filtro);
        } catch (Exception ex) {
            Logger.getLogger(NuevoStockFrame.class.getName()).log(Level.SEVERE, null, ex);
        }
        if (productos != null && !productos.isEmpty()) {
            for (Producto p : productos) {
                combo.addItem(p.getDetalle());
            }
        }
    }

    private void buscar() {
        if (!filtroTxt.getText().isEmpty()) {
            llenarCombo();
        }
    }

    private boolean validar() {
        int row = comboF.getSelectedIndex();
        if (row < 1) {
            return false;
        }
//        if (proveedorTxt.getText().isEmpty()) {
//            proveedorTxt.requestFocus();
//            return false;
//        }
        if (comprobanteTxt.getText().isEmpty()) {
            comprobanteTxt.requestFocus();
            return false;
        }
        if (fechaTxt.getText().isEmpty()) {
            fechaTxt.requestFocus();
            return false;
        }
        int lar = fechaTxt.getText().length();
        if (lar != 10) {
            fechaTxt.requestFocus();
            JOptionPane.showMessageDialog(this, "LA FECHA DEBE INGRESARSE COMPLETA xx/xx/xxxx");
            return false;
        }
        int r = combo.getSelectedIndex();
        if (r < 1) {
            combo.requestFocus();
            JOptionPane.showMessageDialog(this, "DEBE SELECCIONAR UN PRODUCTO");
            return false;
        }
        if (!cantidadTxt.getText().isEmpty()) {
            Float cantidad = Float.valueOf(cantidadTxt.getText());
            if (cantidad < 1) {
                cantidadTxt.requestFocus();
                return false;
            }
        } else {
            cantidadTxt.requestFocus();
            return false;
        }
        if (actualizarChk.isSelected()) {
            if (precioTxt.getText().isEmpty()) {
                precioTxt.requestFocus();
                return false;
            }
            if (impuestoTxt.getText().isEmpty()) {
                impuestoTxt.requestFocus();
                return false;
            }
        }
        return true;
    }

    private void limpiarAbajo() {
        filtroTxt.setText("");
        combo.removeAllItems();
        cantidadTxt.setText("");
        precioTxt.setText("");
        impuestoTxt.setText("");
        finalTxt.setText("");
        actualizarChk.setSelected(false);
        filtroTxt.requestFocus();
    }

    private void calcularPrecios() {
        int row = combo.getSelectedIndex();
        if (row < 1) {
            JOptionPane.showMessageDialog(this, "Seleccione un item para cargar en factura");
            return;
        }
        Producto pr = productos.get(row - 1);
        Double neto = pr.getPrecio();
        Float impuesto = pr.getImpuesto();
        Float porcIva = pr.getAlicuotaIva().getAlicuota();
        Double precioFinal = (neto * (1 + porcIva / 100)) + impuesto;
        precioTxt.setText(df.format(neto));
        impuestoTxt.setText(df.format(impuesto));
        finalTxt.setText(df.format(precioFinal));
    }
