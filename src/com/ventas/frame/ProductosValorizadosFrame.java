    private void llenar() {
        UtilFrame.limpiarTabla(tabla);
        
        rubros = null;
        
        try {
            rubros = new RubroService().getAllRubros();
        } catch (Exception ex) {
            Logger.getLogger(ProductosValorizadosFrame.class.getName()).log(Level.SEVERE, null, ex);
            return;
        }
        llenarCombo();
        
        
    }

    private void volver() {
        MainFrame mf = new MainFrame();
        mf.setVisible(true);
        this.dispose();
    }

    private void llenarCombo() {
        combo.removeAllItems();
        combo.addItem("");
        for(Rubro r:rubros){
            combo.addItem(r.getNombre());
        }
    }

    private void llenarTabla(int row) {
        Rubro rubro = rubros.get(row -1);
        Double totalTop = 0.0;
        List<ProductoTop> productos;
        try {
            productos = new ProductoTopService().getAllProductoTabacoTopActivos2(rubro);
        } catch (Exception ex) {
            Logger.getLogger(ProductosValorizadosFrame.class.getName()).log(Level.SEVERE, null, ex);
            return;
        }
        DefaultTableModel tbl = (DefaultTableModel) tabla.getModel();
        for (ProductoTop pt : productos) {
            Double neto = pt.getPrecio();
            Double iva = neto * .21;
            Float stock = pt.getStock();
            Float impuesto = pt.getImpuesto();
            iva = UtilFactura.calcularRedondeo(iva);
            Double precioUnitario = neto + iva + impuesto;
            precioUnitario = UtilFactura.calcularRedondeo(precioUnitario);
            Integer fraccion = pt.getFraccion();
            Double precioFraccion = precioUnitario * fraccion;
            precioFraccion = UtilFactura.calcularRedondeo(precioFraccion);
            Double precioStock = precioUnitario * stock;
            precioStock = UtilFactura.calcularRedondeo(precioStock);
            Object o[] = new Object[6];
            o[0] = pt.getCodigo();
            o[1] = pt.getDetalle();
            o[2] = df.format(precioUnitario);
            o[3] = df.format(precioFraccion);
            o[4] = df_float.format(stock);
            o[5] = df.format(precioStock);
            totalTop += precioStock;
            tbl.addRow(o);
        }
        Object o[] = new Object[5];
//            o[0]=pt.getCodigo();
//            o[1]=pt.getDetalle();
//            o[2]=df.format(precioUnitario);
        o[4] = df.format(totalTop);
//            totalTop+=precioFraccion;
        tbl.addRow(o);
        tabla.setModel(tbl);
    }
